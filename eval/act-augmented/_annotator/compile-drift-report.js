#!/usr/bin/env node
/**
 * compile-drift-report.js — aggregate the per-SC drift-report/*.json files into a
 * single human-facing report (DRIFT-REPORT.md), surfacing the not-aligned cases
 * (which need a human decision) and listing the stale-desc descriptions that were
 * auto-corrected via description-overrides/.
 */
const fs = require('fs');
const path = require('path');
const DIR = __dirname;
const REPORT_DIR = path.join(DIR, 'drift-report');
const DESC_DIR = path.join(DIR, 'description-overrides');

const scs = fs.readdirSync(REPORT_DIR).filter(f => /^\d+\.\d+\.\d+\.json$/.test(f))
  .map(f => f.replace('.json', '')).sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));

const rows = [];
const notAligned = [];
const staleDesc = [];
const shortfalls = [];
let tA = 0, tS = 0, tN = 0, tP = 0;

for (const sc of scs) {
  const rep = JSON.parse(fs.readFileSync(path.join(REPORT_DIR, `${sc}.json`), 'utf8'));
  // coverage check: report must cover every page in the drift-input extract
  try {
    const input = JSON.parse(fs.readFileSync(path.join(DIR, 'drift-input', `${sc}.json`), 'utf8'));
    const have = new Set(Object.keys(rep));
    const missing = input.filter(e => !have.has(`${e.aspect}/${e.caseId}`)).map(e => `${e.aspect}/${e.caseId}`);
    if (missing.length) shortfalls.push({ sc, have: have.size, want: input.length, missing });
  } catch {}
  let desc = {};
  try { desc = JSON.parse(fs.readFileSync(path.join(DESC_DIR, `${sc}.json`), 'utf8')); } catch {}
  let a = 0, s = 0, n = 0;
  for (const [key, v] of Object.entries(rep)) {
    tP++;
    if (v.status === 'aligned') { a++; }
    else if (v.status === 'stale-desc') { s++; staleDesc.push({ sc, key, reason: v.reason, note: (desc[key] || {}).note || '' }); }
    else if (v.status === 'not-aligned') { n++; notAligned.push({ sc, key, reason: v.reason }); }
  }
  tA += a; tS += s; tN += n;
  rows.push({ sc, total: a + s + n, a, s, n });
}

const url = (sc, key) => `/eval/act-augmented/${sc}/pages/${key.split('/')[0]}/${key.split('/')[1]}.html`;

let md = `# HTML-vs-mechanism drift audit\n\n`;
md += `Every act-augmented page was read and compared against its \`mechanism\`/\`scenario\`/\`expected\`.\n\n`;
md += `- **aligned** — HTML demonstrates the described failure/control; nothing to do.\n`;
md += `- **stale-desc** — HTML is fine, only the prose drifted → **auto-corrected** in \`description-overrides/\` (shown corrected in the annotator).\n`;
md += `- **not-aligned** — HTML does NOT demonstrate the described aspect → **left for you to decide** (regenerate the page, remap the aspect, or rewrite the description).\n\n`;
md += `**Totals: ${tP} pages — ${tA} aligned · ${tS} stale-desc (fixed) · ${tN} not-aligned (need decision)** across ${scs.length} SCs.\n\n`;

md += `## Per-SC summary\n\n| SC | pages | aligned | stale-desc (fixed) | not-aligned (decide) |\n|---|--:|--:|--:|--:|\n`;
for (const r of rows) md += `| ${r.sc} | ${r.total} | ${r.a} | ${r.s} | ${r.n ? '**' + r.n + '**' : '0'} |\n`;
md += `| **all** | **${tP}** | **${tA}** | **${tS}** | **${tN}** |\n\n`;

md += `## ⚠ Not-aligned — needs your decision (${notAligned.length})\n\n`;
md += `The page on disk does not match the written aspect/description. Options per case: (a) regenerate the page to match, (b) move it to the aspect it actually demonstrates, or (c) rewrite the description.\n\n`;
let curSc = null;
for (const x of notAligned.sort((p, q) => (p.sc + p.key).localeCompare(q.sc + q.key, undefined, { numeric: true }))) {
  if (x.sc !== curSc) { curSc = x.sc; md += `\n### SC ${x.sc}\n\n`; }
  md += `- **${x.key}** — ${x.reason}  \n  [open page](${url(x.sc, x.key)})\n`;
}

md += `\n## Stale-desc — descriptions auto-corrected (${staleDesc.length})\n\n`;
md += `Page is a valid case; the mechanism/scenario text drifted and was rewritten to match the HTML (see \`description-overrides/<sc>.json\`).\n\n`;
curSc = null;
for (const x of staleDesc.sort((p, q) => (p.sc + p.key).localeCompare(q.sc + q.key, undefined, { numeric: true }))) {
  if (x.sc !== curSc) { curSc = x.sc; md += `\n### SC ${x.sc}\n\n`; }
  md += `- **${x.key}** — ${x.note || x.reason}\n`;
}
md += `\n---\n_Generated by compile-drift-report.js from drift-report/*.json + description-overrides/*.json._\n`;

const out = path.join(DIR, 'DRIFT-REPORT.md');
fs.writeFileSync(out, md);
console.log(`Wrote ${path.relative(path.resolve(DIR, '..', '..', '..'), out)}`);
console.log(`  SCs compiled: ${scs.length}/22   pages: ${tP}`);
console.log(`  aligned ${tA} · stale-desc ${tS} · not-aligned ${tN}`);
if (scs.length < 22) console.log(`  (waiting on ${22 - scs.length} SCs)`);
if (shortfalls.length) {
  console.log(`\n  COVERAGE SHORTFALLS (re-run these SCs):`);
  for (const s of shortfalls) console.log(`    ${s.sc}: ${s.have}/${s.want}  missing ${s.missing.length} (${s.missing.slice(0, 4).join(', ')}${s.missing.length > 4 ? '…' : ''})`);
} else if (scs.length === 22) {
  console.log(`  Coverage complete: all SCs cover every page.`);
}
